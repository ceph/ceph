def test_jaeger_config_ipv6_valid_yaml(cephadm_module: CephadmOrchestrator):
    """server_urls must be valid YAML when ES URLs contain IPv6 brackets.

    build_url wraps IPv6 addresses in brackets (http://[addr]:port).  The
    old template  server_urls: [http://[addr]:9200]  makes the inner brackets
    invalid YAML, so jaeger won't start on any IPv6 cluster.  The fix must
    produce parseable YAML whose server_urls is a proper list containing the
    bracketed URL.
    """
    import yaml
    from unittest.mock import MagicMock
    from cephadm.services.cephadmservice import CephadmDaemonDeploySpec, DaemonDeployContext
    from cephadm.services.service_registry import service_registry
    from orchestrator import DaemonDescription

    ipv6_addr = 'fce:9af7:a667:7286:4917:b8d3:34df:8373'
    expected_url = f'http://[{ipv6_addr}]:9200'

    # Simulate a managed ES daemon with an IPv6 address.
    dd = DaemonDescription(
        daemon_type='elasticsearch', daemon_id='host-a',
        hostname='host-a', ports=[9200],
    )
    dd.ip = ipv6_addr
    cephadm_module.cache.get_daemons_by_type = MagicMock(return_value=[dd])

    service = service_registry.get_service('jaeger')
    daemon_spec = CephadmDaemonDeploySpec(
        host='test', daemon_id='test',
        service_name='jaeger', daemon_type='jaeger',
    )
    spec = TracingSpec(service_type='jaeger')
    deploy_ctx = DaemonDeployContext(daemon_spec, spec)
    config_blobs, _ = service.generate_config(deploy_ctx)

    config_text = config_blobs['files']['config.yaml']
    # Must parse without raising a yaml.YAMLError.
    parsed = yaml.safe_load(config_text)
    server_urls = (
        parsed['extensions']['jaeger_storage']['backends']
        ['some_storage']['elasticsearch']['server_urls']
    )
    assert isinstance(server_urls, list), 'server_urls must be a YAML sequence'
    assert server_urls == [expected_url]
