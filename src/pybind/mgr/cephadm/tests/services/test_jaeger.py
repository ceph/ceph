def test_jaeger_agent_get_dependencies():
    from unittest.mock import MagicMock
    from cephadm.services.jaeger import JaegerService
    from ceph.deployment.service_spec import TracingSpec
    from orchestrator import DaemonDescription

    mgr = MagicMock()
    mgr.get_ceph_option.return_value = 4317

    # Two ES daemons with known IPs/ports (provided in reverse order to
    # verify that get_dependencies returns a sorted list).
    dd_b = DaemonDescription(daemon_type='elasticsearch', daemon_id='host-b',
                             hostname='host-b', ports=[9200])
    dd_b.ip = '10.0.0.2'
    dd_a = DaemonDescription(daemon_type='elasticsearch', daemon_id='host-a',
                             hostname='host-a', ports=[9200])
    dd_a.ip = '10.0.0.1'
    mgr.cache.get_daemons_by_type.return_value = [dd_b, dd_a]

    spec = TracingSpec(service_type='jaeger', es_nodes='192.168.0.1:9200')
    result = JaegerService.get_dependencies(mgr, spec)

    assert result == [
        'elasticsearch.host-a:10.0.0.1:9200',
        'elasticsearch.host-b:10.0.0.2:9200',
        'es_nodes:192.168.0.1:9200',
        'jaeger_agent_port:4317',
    ]


