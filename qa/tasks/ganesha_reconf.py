"""
reconfigure a ganesha server

Enables debug logging for the ganesha server and for the libcephfs
client instances used by the CephFS FSAL. Both log to files under the
cluster log directory (/var/log/ceph/<fsid>) so that they are archived
with the rest of the ceph logs. Optionally enables NFSv4 delegations,
which the ganesha config generated by cephadm turns off. Its NFSv4
block cannot be overridden by the nfs cluster user config (ganesha
allows only one), so a custom cephadm ganesha.conf template is used.

  - ganesha-reconf:
      cluster_id: <nfs cluster id>
      client_log_level: 20         # libcephfs debug_client; 0 disables
      server_log_level: FULL_DEBUG # ganesha LOG level; 'none' disables
      delegations: none            # export delegations: none, R, W or RW
      timeout: 300                 # seconds to wait for the redeploy
"""

import json
import logging
from io import StringIO

from teuthology.contextutil import safe_while
from teuthology.misc import deep_merge
from teuthology.task import Task
from teuthology import misc

from tasks.cephadm import _shell

log = logging.getLogger(__name__)

GANESHA_TEMPLATE = '/usr/share/ceph/mgr/cephadm/templates/services/nfs/ganesha.conf.j2'
GANESHA_TEMPLATE_KEY = 'mgr/cephadm/services/nfs/ganesha.conf'

class GaneshaReconf(Task):
    def __init__(self, ctx, config):
        super(GaneshaReconf, self).__init__(ctx, config)
        self.log = log
        self.custom_template = False

    def setup(self):
        super(GaneshaReconf, self).setup()

    def _ceph(self, *args, stdin=None):
        proc = self.mon0_remote.run(args=['ceph', *args], stdin=stdin,
                                    stdout=StringIO(), wait=True)
        return proc.stdout.getvalue()

    def _nfs_daemons(self, service_name):
        res = self._ceph('orch', 'ps', '--service_name', service_name,
                         '--refresh', '--format', 'json')
        return json.loads(res)

    def _set_server_log(self, cluster_id, level):
        # LOG is the only block in the user config, so the nfs module does
        # not restart the service. The daemon gets redeployed when the
        # service spec is updated and picks the config up on start.
        log_conf = f"""LOG {{
    COMPONENTS {{
        ALL = {level};
    }}
    FACILITY {{
        name = FILE;
        destination = "/var/log/ceph/ganesha.{cluster_id}.log";
        enable = active;
    }}
}}
"""
        log.info(f'ganesha user config:\n{log_conf}')
        self._ceph('nfs', 'cluster', 'config', 'set', cluster_id, '-i', '-',
                   stdin=log_conf)

    def _set_delegations(self, delegations):
        # start from the template shipped with the cephadm mgr module in use
        proc = _shell(self.ctx, 'ceph', self.mon0_remote, ['cat', GANESHA_TEMPLATE],
                      stdout=StringIO())
        template = proc.stdout.getvalue()
        disabled = 'Delegations = false;'
        assert template.count(disabled) == 1, \
            f'cannot find "{disabled}" in {GANESHA_TEMPLATE}'
        # mgr/nfs exports carry no delegations setting of their own
        template = template.replace(disabled, 'Delegations = true;')
        template += f"""
EXPORT_DEFAULTS {{
        Delegations = {delegations};
}}
"""
        log.info(f'custom ganesha.conf template:\n{template}')
        self._ceph('config-key', 'set', GANESHA_TEMPLATE_KEY, '-i', '-',
                   stdin=template)
        self.custom_template = True

    def _update_spec(self, service_name, client_log_level):
        res = self._ceph('orch', 'ls', '--service-name', service_name,
                         '--export', '--format', 'json')
        specs = json.loads(res)
        assert len(specs) == 1, f'unexpected specs for {service_name}: {specs}'
        nfs_spec = specs[0]
        # enabling the cephfs client log also mounts the host log directory
        # into the container which the ganesha log file needs as well.
        nfs_spec.setdefault('spec', {})
        nfs_spec['spec']['enable_cephfs_client_log'] = True
        nfs_spec['spec']['cephfs_client_log_level'] = client_log_level
        log.info(f'applying nfs spec: {json.dumps(nfs_spec)}')
        self._ceph('orch', 'apply', '-i', '-', stdin=json.dumps(nfs_spec))

    def _wait_for_redeploy(self, service_name, before, timeout):
        started = {d['daemon_name']: d.get('started') for d in before}
        with safe_while(sleep=10, tries=timeout // 10,
                        action=f'wait for {service_name} redeploy') as proceed:
            while proceed():
                daemons = self._nfs_daemons(service_name)
                pending = [d['daemon_name'] for d in daemons
                           if d.get('status_desc') != 'running' or
                           d.get('started') == started.get(d['daemon_name'])]
                if daemons and not pending:
                    return daemons
                log.info(f'waiting for redeploy of {pending}')

    def begin(self):
        super(GaneshaReconf, self).begin()
        log.info('reconfiguring ganesha server')

        ganesha_config = self.config
        log.info(f'ganesha_config is {ganesha_config}')
        overrides = self.ctx.config.get('overrides', {}).get('ganesha-reconf', {})
        log.info(f'overrides is {overrides}')

        deep_merge(ganesha_config, overrides)
        log.info(f'ganesha_config is {ganesha_config}')

        first_mon = misc.get_first_mon(self.ctx, None)
        (self.mon0_remote,) = self.ctx.cluster.only(first_mon).remotes.keys()

        cluster_id = ganesha_config['cluster_id']
        client_log_level = int(ganesha_config.get('client_log_level', 20))
        server_log_level = str(ganesha_config.get('server_log_level', 'FULL_DEBUG'))
        delegations = str(ganesha_config.get('delegations', 'none'))
        timeout = int(ganesha_config.get('timeout', 300))

        enable_log = client_log_level != 0 or server_log_level.lower() != 'none'
        enable_deleg = delegations.lower() != 'none'
        if not enable_log and not enable_deleg:
            log.info('nothing to reconfigure')
            return

        service_name = f'nfs.{cluster_id}'
        daemons = self._nfs_daemons(service_name)
        log.debug(f'nfs daemons before reconf: {daemons}')

        # everything below is picked up when the daemons get redeployed
        if server_log_level.lower() != 'none':
            self._set_server_log(cluster_id, server_log_level)
        if enable_deleg:
            self._set_delegations(delegations)

        if enable_log:
            self._update_spec(service_name, client_log_level)
        else:
            self._ceph('orch', 'redeploy', service_name)
        daemons = self._wait_for_redeploy(service_name, daemons, timeout)
        log.info(f'nfs daemons after reconf: {daemons}')

    def end(self):
        super(GaneshaReconf, self).end()
        if self.custom_template:
            self._ceph('config-key', 'rm', GANESHA_TEMPLATE_KEY)
            self.custom_template = False

task = GaneshaReconf
